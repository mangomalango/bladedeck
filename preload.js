'use strict';
const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('bladedeck', {
  load: () => ipcRenderer.invoke('load'),
  save: (lib) => ipcRenderer.invoke('save', lib),
  launch: (payload) => ipcRenderer.invoke('launch', payload),
  pick: (opts) => ipcRenderer.invoke('pick', opts),
  scanSteam: (p) => ipcRenderer.invoke('scan-steam', p),
  scanRoms: (opts) => ipcRenderer.invoke('scan-roms', opts),
  setMode: (m) => ipcRenderer.invoke('set-mode', m),
  quit: () => ipcRenderer.invoke('quit'),
  openThemes: () => ipcRenderer.invoke('open-themes'),
  openCss: () => ipcRenderer.invoke('open-css'),
  pathForFile: (f) => webUtils.getPathForFile(f),
  scanGog: (dirs) => ipcRenderer.invoke('scan-gog', dirs),
  downloads: () => ipcRenderer.invoke('downloads'),
  minimize: () => ipcRenderer.invoke('minimize'),
  findLaunchers: () => ipcRenderer.invoke('find-launchers'),
  captureSource: () => ipcRenderer.invoke('capture-source'),
  clipOpen: (id) => ipcRenderer.invoke('clip-open', id),
  clipChunk: (key, buf) => ipcRenderer.invoke('clip-chunk', key, buf),
  clipClose: (key) => ipcRenderer.invoke('clip-close', key),
  steamShots: (appid) => ipcRenderer.invoke('steam-shots', appid),
  copy: (t) => ipcRenderer.invoke('copy', t),
  openLink: (u) => ipcRenderer.invoke('open-link', u),
  peekBack: () => ipcRenderer.invoke('peek-back'),
  peekToggle: () => ipcRenderer.invoke('peek-toggle'),
  peekConfig: (o) => ipcRenderer.invoke('peek-config', o),
  peekMode: () => ipcRenderer.invoke('peek-mode'),
  captureWindow: (caption, ask) => ipcRenderer.invoke('capture-window', caption, ask),
  snap: () => ipcRenderer.invoke('snap'),
  musicDefault: () => ipcRenderer.invoke('music-default'),
  musicScan: (dir) => ipcRenderer.invoke('music-scan', dir),
  onPeek: (cb) => ipcRenderer.on('peek', (_e, d) => cb(d)),
  presence: (p) => ipcRenderer.invoke('presence', p),
  netInfo: () => ipcRenderer.invoke('net-info'),
  netPeers: () => ipcRenderer.invoke('net-peers'),
  netHello: (host) => ipcRenderer.invoke('net-hello', host),
  netPoke: (host, body) => ipcRenderer.invoke('net-poke', host, body),
  onPoked: (cb) => ipcRenderer.on('poked', (_e, d) => cb(d)),
  onEnded: (cb) => ipcRenderer.on('launch-ended', (_e, d) => cb(d)),
  onDownloads: (cb) => ipcRenderer.on('downloads', (_e, d) => cb(d)),
  onReturned: (cb) => ipcRenderer.on('returned', () => cb())
});
